import Foundation

/// Fail-closed verifier for the exact Apple built-in trackpad HID report
/// layout understood by AppleTrackpadRawReportDecoder.
enum AppleTrackpadReportDescriptorVerifier {
    enum VerificationError: Error, Equatable, Sendable {
        case unsupportedDescriptor
    }

    /// Proven 78-byte Report-ID-2 layout:
    /// 3 button bits + 5 padding, relative X/Y, 4 constant bytes, FF00:0C.
    static let supportedDescriptor = Data([
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01,
        0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
        0x15, 0x00, 0x25, 0x01, 0x85, 0x02, 0x95, 0x03,
        0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05,
        0x81, 0x01, 0x05, 0x01, 0x09, 0x30, 0x09, 0x31,
        0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x02,
        0x81, 0x06, 0x95, 0x04, 0x75, 0x08, 0x81, 0x01,
        0x06, 0x00, 0xFF, 0x09, 0x25, 0xA1, 0x01, 0x06, 0x00,
        0xFF, 0x09, 0x0C, 0x75, 0x08, 0x96, 0xD7, 0x06,
        0x81, 0x22, 0xC0, 0xC0, 0xC0
    ])

    static func verify(_ descriptor: Data) throws {
        guard descriptor == supportedDescriptor else {
            throw VerificationError.unsupportedDescriptor
        }
    }
}
